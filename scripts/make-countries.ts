// Bake the country outlines into src/data/countries.ts, so the package ships its data and never fetches at runtime.
// Geometry: world-atlas (Natural Earth 1:110m, public domain). Codes and English/Japanese names: kuni, matched by ISO numeric id.
// Coordinates are rounded to one decimal (~11 km): under a pixel on any globe a page would draw, and a fraction of the bytes.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { feature } from "topojson-client";
import { country } from "@johnmorrisdotca/kuni";
import type { GeometryCollection, Topology } from "topojson-specification";
import type { FeatureCollection, Geometry } from "geojson";

interface CountryProps {
  name: string;
  ja: string | null;
  alpha2: string | null;
}

const round = (n: number): number => Math.round(n * 10) / 10;

function roundGeometry(geometry: Geometry): Geometry {
  const walk = (value: unknown): unknown => {
    if (typeof value === "number") return round(value);
    if (Array.isArray(value)) return value.map(walk);
    return value;
  };
  if (geometry.type === "GeometryCollection") return geometry;
  return { ...geometry, coordinates: walk(geometry.coordinates) } as Geometry;
}

const topo = JSON.parse(await readFile("node_modules/world-atlas/countries-110m.json", "utf8")) as Topology;
const collection = feature(topo, topo.objects.countries as GeometryCollection) as unknown as FeatureCollection;

let matched = 0;
const features = collection.features.map((f) => {
  const id = String(f.id ?? "");
  const k = id ? country(id) : null;
  if (k) matched += 1;
  const props: CountryProps = {
    name: k?.name.en ?? (f.properties?.name as string) ?? id,
    ja: k?.name.ja ?? null,
    alpha2: k?.alpha2 ?? null,
  };
  return { type: "Feature" as const, geometry: roundGeometry(f.geometry), properties: props };
});

const out: FeatureCollection<Geometry, CountryProps> = { type: "FeatureCollection", features };
const body = `// Generated by scripts/make-countries.ts. Do not edit by hand: run \`pnpm countries\`.
// Outlines: Natural Earth 1:110m (public domain), via world-atlas. Names and codes: kuni.
import type { FeatureCollection, Geometry } from "geojson";
import type { CountryProps } from "../types.ts";

export const COUNTRIES: FeatureCollection<Geometry, CountryProps> = ${JSON.stringify(out)} as FeatureCollection<Geometry, CountryProps>;
`;

await mkdir(new URL("../src/data/", import.meta.url), { recursive: true });
await writeFile(new URL("../src/data/countries.ts", import.meta.url), body, "utf8");
console.log(`countries: ${features.length} features, ${matched} matched to kuni, ${(Buffer.byteLength(body) / 1024).toFixed(0)} KB`);
